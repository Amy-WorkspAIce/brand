"""Generate tokens/tokens.css and fonts/fonts.css from tokens/tokens.json.

Run after editing tokens.json:  python scripts/build_css.py
Dark is the default theme. Light applies with data-theme="light" on <html>, or when the
system prefers light and no data-theme is set ("system" mode in apps).
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
tokens = json.loads((ROOT / "tokens" / "tokens.json").read_text(encoding="utf-8"))

ALIAS = re.compile(r"^\{([A-Za-z0-9_.-]+)\}$")


def css_value(value: str) -> str:
    m = ALIAS.match(value)
    return f"var(--{m.group(1)})" if m else value


def themed(theme: str) -> list[str]:
    out = []
    for family in ("color", "shadow"):
        for t in tokens.get(family, {}).get("tokens", []):
            v = t["value"]
            if isinstance(v, dict):
                if theme in v:
                    out.append(f"  --{t['name']}: {css_value(v[theme])};")
            elif theme == "dark":
                out.append(f"  --{t['name']}: {css_value(v)};")
    return out


static = [f"  --font-{k}: {v};" for k, v in tokens["type"]["families"].items()]
for family in ("spacing", "radius", "cut"):
    static += [f"  --{t['name']}: {t['value']};" for t in tokens.get(family, {}).get("tokens", [])]
for group in tokens["type"]["groups"]:
    for s in group["styles"]:
        n = s["name"]
        static.append(
            f"  --type-{n}: {s['fontWeight']} {s['fontSize']}/{s['lineHeight']} var(--font-{group['family']});"
        )
        if s.get("letterSpacing"):
            static.append(f"  --type-{n}-tracking: {s['letterSpacing']};")

dark, light = "\n".join(themed("dark")), "\n".join(themed("light"))
css = f"""/* {tokens['name']} design tokens: generated from tokens/tokens.json by scripts/build_css.py. Do not edit. */

:root {{
  color-scheme: dark;
{chr(10).join(static)}
{dark}
}}

:root[data-theme="light"] {{
  color-scheme: light;
{light}
}}

@media (prefers-color-scheme: light) {{
  :root:not([data-theme]) {{
    color-scheme: light;
{chr(10).join("  " + line for line in light.splitlines())}
  }}
}}

/* The clipped corner: cut the top-left and bottom-right corners of filled shapes. */
.cut-sm {{ clip-path: polygon(var(--cut-sm) 0, 100% 0, 100% calc(100% - var(--cut-sm)), calc(100% - var(--cut-sm)) 100%, 0 100%, 0 var(--cut-sm)); }}
.cut-md {{ clip-path: polygon(var(--cut-md) 0, 100% 0, 100% calc(100% - var(--cut-md)), calc(100% - var(--cut-md)) 100%, 0 100%, 0 var(--cut-md)); }}
"""
(ROOT / "tokens" / "tokens.css").write_text(css, encoding="utf-8", newline="\n")

faces = []
for f in tokens["type"]["fonts"]:
    faces.append(
        "@font-face {\n"
        f"  font-family: \"{f['family']}\";\n"
        f"  src: url(\"{pathlib.Path(f['file']).name}\") format(\"woff2\");\n"
        f"  font-weight: {f['weight']};\n"
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        "}"
    )
(ROOT / "fonts" / "fonts.css").write_text(
    "/* Self-hosted brand fonts (SIL Open Font License). Generated by scripts/build_css.py. */\n\n"
    + "\n\n".join(faces)
    + "\n",
    encoding="utf-8",
    newline="\n",
)
print("wrote tokens/tokens.css and fonts/fonts.css")
